-- ADDRESS
CREATE TABLE ADDRESS (
    ADDRESS_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ADDRESS_TYPE VARCHAR2(30) NOT NULL,
    ADDRESS_LINE1 VARCHAR2(150) NOT NULL,
    ADDRESS_LINE2 VARCHAR2(150),
    CITY VARCHAR2(80) NOT NULL,
    THALUK VARCHAR2(80),
    ADD_STATE VARCHAR2(80) NOT NULL,
    COUNTRY VARCHAR2(80) NOT NULL,
    PINCODE VARCHAR2(10) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- EMPLOYEE
CREATE TABLE EMPLOYEE (
    EMPLOYEE_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_NAME VARCHAR2(50) NOT NULL,
    EMPLOYEE_LEVEL VARCHAR2(2) NOT NULL,
    ADDRESS_ID NUMBER(19),
    PRIMARY_PHONE_NUMBER NUMBER(15) NOT NULL,
    SECONDARY_PHONE_NUMBER NUMBER(15),
    DATE_OF_JOINING NUMBER(19) NOT NULL,
    DATE_OF_RESIGN NUMBER(19),
    EMPLOYEE_STATUS VARCHAR2(10),
    EMAIL VARCHAR2(50) UNIQUE,

    CONSTRAINT FK_EMPLOYEE_ADDRESS
    FOREIGN KEY (ADDRESS_ID)
    REFERENCES ADDRESS(ADDRESS_ID)
    ON DELETE SET NULL
);

-- SALARY
CREATE TABLE SALARY (
    EMPLOYEE_ID NUMBER(19) PRIMARY KEY,
    EMPLOYEE_LEVEL VARCHAR2(2) NOT NULL,
    SALARY_PER_HOUR NUMBER(10,2) NOT NULL,

    CONSTRAINT FK_SALARY_EMPLOYEE
    FOREIGN KEY (EMPLOYEE_ID)
    REFERENCES EMPLOYEE(EMPLOYEE_ID)
    ON DELETE CASCADE
);

-- PROJECT
CREATE TABLE PROJECT (
    PROJECT_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PROJECT_CODE VARCHAR2(20) UNIQUE NOT NULL,
    PROJECT_NAME VARCHAR2(100) NOT NULL,
    ADDRESS_ID NUMBER(19),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT FK_PROJECT_ADDRESS
    FOREIGN KEY (ADDRESS_ID)
    REFERENCES ADDRESS(ADDRESS_ID)
    ON DELETE SET NULL
);

-- ATTENDANCE
CREATE TABLE ATTENDANCE (
    ATTENDANCE_ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMPLOYEE_ID NUMBER(19) NOT NULL,
    PROJECT_ID NUMBER(19) NOT NULL,
    WORK_DATE NUMBER(19) NOT NULL,
    WORKDAYS NUMBER(10,2) NOT NULL,

    CONSTRAINT UQ_ATTENDANCE UNIQUE (EMPLOYEE_ID, PROJECT_ID, WORK_DATE),

    CONSTRAINT FK_ATTENDANCE_EMPLOYEE
    FOREIGN KEY (EMPLOYEE_ID)
    REFERENCES EMPLOYEE(EMPLOYEE_ID)
    ON DELETE CASCADE,

    CONSTRAINT FK_ATTENDANCE_PROJECT
    FOREIGN KEY (PROJECT_ID)
    REFERENCES PROJECT(PROJECT_ID)
    ON DELETE CASCADE
);

CREATE INDEX IDX_ATTENDANCE_EMPLOYEE_ID
ON ATTENDANCE(EMPLOYEE_ID);